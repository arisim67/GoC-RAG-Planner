export function icon(name, cls = '') {
  const p = PATHS[name];
  if (!p) return '';
  return `<svg class="icon${cls ? ' ' + cls : ''}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${p}</svg>`;
}

// Change a button's words (e.g. "Saving...") without removing its icon. Returns the previous words.
export function setBtnLabel(btn, text) {
  if (!btn) return '';
  const label = btn.querySelector('.btn-label');
  const target = label || btn;
  const before = target.textContent;
  target.textContent = text;
  return before;
}
